export type MessageKey = keyof typeof dict.en;

export function translate(language: Language, key: MessageKey): string {
  return dict[language][key] ?? dict.en[key];
}

export function formatDuration(ms: number, language: Language): string {
  const [divisor, unit]: [number, string] =
    ms >= 86_400_000
      ? [86_400_000, "day"]
      : ms >= 3_600_000
        ? [3_600_000, "hour"]
        : ms >= 60_000
          ? [60_000, "minute"]
          : [1_000, "second"];
  return new Intl.NumberFormat(language, {
    style: "unit",
    unit,
    unitDisplay: "short",
    maximumFractionDigits: 1,
  }).format(ms / divisor);
}
