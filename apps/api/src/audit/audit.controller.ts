import { Controller, Get, Query, UseGuards } from '@nestjs/common';
import { AuditService } from './audit.service.js';
import type { AuthUser } from '../auth/auth.types.js';
import { CurrentUser } from '../auth/current-user.decorator.js';
import { PolicyService } from '../auth/policy.service.js';
import { PrismaService } from '../prisma/prisma.service.js';

@Controller('audit')
export class AuditController {
  constructor(
    private readonly auditService: AuditService,
    private readonly policy: PolicyService,
    private readonly prisma: PrismaService,
  ) {}

  /**
   * Returns paginated system audit logs according to role rank and area scope.
   */
  @Get('logs')
  async listLogs(
    @CurrentUser() user: AuthUser,
    @Query('take') takeQuery?: string,
    @Query('skip') skipQuery?: string,
    @Query('category') category?: string,
  ) {
    const take = Math.min(Number(takeQuery) || 50, 100);
    const skip = Number(skipQuery) || 0;
    const userRank = this.policy.getUserRank(user);

    // Record that user viewed audit logs ("auditing the auditor")
    await this.auditService.record({
      actor: user,
      action: 'audit.logs.view',
      result: 'SUCCESS',
      entityType: 'AuditLog',
    });

    const where: any = {};

    // Rank enforcement: users can only see audit events generated by actors with rank <= userRank
    // (Except their own actions which they can always see)
    if (!this.policy.isAdmin(user)) {
      where.OR = [
        { actorId: user.id },
        { actorRank: { lte: userRank } },
      ];

      // Area scope: AREA_LEAD only sees logs within their area paths
      if (user.globalRole === 'AREA_LEAD') {
        const scopePaths = await this.policy.getScopeAreaPaths(user);
        if (scopePaths && scopePaths.length > 0) {
          where.AND = [
            {
              OR: [
                { areaPath: null },
                ...scopePaths.map((sp) => ({ areaPath: { startsWith: sp } })),
              ],
            },
          ];
        }
      } else if (user.globalRole === 'EMPLOYEE') {
        // Employee can only see their own logs
        where.OR = [{ actorId: user.id }];
      }
    }

    if (category === 'security') {
      where.action = { startsWith: 'auth.' };
    }

    const [logs, total] = await Promise.all([
      this.prisma.auditLog.findMany({
        where,
        orderBy: { seq: 'desc' },
        take,
        skip,
      }),
      this.prisma.auditLog.count({ where }),
    ]);

    return {
      logs,
      total,
      take,
      skip,
    };
  }

  /**
   * Verifies cryptographic hash chain integrity (Admin only).
   */
  @Get('integrity')
  async verifyIntegrity(@CurrentUser() user: AuthUser) {
    if (!this.policy.isAdmin(user)) {
      return { valid: false, error: 'Admin role required' };
    }

    const result = await this.auditService.verifyChain();

    await this.auditService.record({
      actor: user,
      action: 'audit.integrity.verify',
      result: result.valid ? 'SUCCESS' : 'ERROR',
      entityType: 'AuditLog',
      after: { ...result },
    });

    return result;
  }
}
